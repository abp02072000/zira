export type T = typeof translations.fr;

interface LangContextValue {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: T;
}

const LangContext = createContext<LangContextValue | null>(null);

export function LangProvider({ children }: { children: ReactNode }) {
  const saved = (localStorage.getItem("zira-lang") ?? "fr") as Lang;
  const [lang, setLangState] = useState<Lang>(saved);

  function setLang(l: Lang) {
    setLangState(l);
    localStorage.setItem("zira-lang", l);
  }

  return (
    <LangContext.Provider value={{ lang, setLang, t: translations[lang] as unknown as T }}>
      {children}
    </LangContext.Provider>
  );
}

export function useLang() {
  const ctx = useContext(LangContext);
  if (!ctx) throw new Error("useLang must be used inside LangProvider");
  return ctx;
}
